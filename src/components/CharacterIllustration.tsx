/**
 * Hero renders this component twice at once (a mobile layout + a desktop
 * layout, one hidden via CSS at any given breakpoint) — so every id in the
 * markup above would otherwise collide across instances. Duplicate ids mean
 * a url(#id) clip-path/filter reference can resolve to the *other*
 * instance's definition depending on DOM order, which silently breaks the
 * eye clip / cheek dot clip. Suffix every id and every url(#id) reference
 * with a per-instance token so each mounted copy is fully self-contained.
 */
function namespaceSvg(markup: string, uid: string) {
  return markup
    .replace(/\bid="([\w-]+)"/g, (_m, id: string) => `id="${id}-${uid}"`)
    .replace(/url\(#([\w-]+)\)/g, (_m, id: string) => `url(#${id}-${uid})`);
}

/**
 * Tunables straight from the design's rigged prototype — eye travel range,
 * brow rotation/lift, mouth shift, and how "lazy" the follow-easing feels.
 */
const CFG = {
  pupilX: 3.4,
  // Kept well inside the eyeOpenL/R clip shapes so the iris never pokes past
  // the eyelash line when gazing sharply up or down (the clip is an almond
  // ~7-8 units tall, so travel is capped comfortably below that half-height).
  pupilY: 1.5,
  browRot: 4.5,
  browLift: 1.6,
  mouthShift: 1.2,
  follow: 0.1,
  browFollow: 0.06,
};

export default function CharacterIllustration({
  className = "",
}: {
  className?: string;
}) {
  const rootRef = useRef<HTMLDivElement>(null);
  const rawUid = useId();
  const uid = useMemo(() => rawUid.replace(/[^a-zA-Z0-9]/g, ""), [rawUid]);
  const markup = useMemo(() => namespaceSvg(SVG_MARKUP, uid), [uid]);

  useEffect(() => {
    const root = rootRef.current;
    if (!root) return;

    const svg = root.querySelector("svg");
    if (!svg) return;

    const $ = (id: string) => root.querySelector<SVGElement>(`#${id}-${uid}`);
    const pL = $("pupilL");
    const pR = $("pupilR");
    const eL = $("eyeL");
    const eR = $("eyeR");
    const bL = $("browL");
    const bR = $("browR");
    const mouth = $("mouth");
    const chL = $("chiliL");
    const chR = $("chiliR");
    const head = $("Layer_1-2");
    const turbulence = root.querySelector("feTurbulence");
    const displacement = root.querySelector("feDisplacementMap");
    if (!pL || !pR || !eL || !eR || !bL || !bR || !mouth || !chL || !chR || !head) {
      return;
    }

    // Chrome/WebKit bug: elements referenced as `url(#id)` for clip-path /
    // filter (the eye clip masks + the forehead flame filter) can stop
    // resolving once the page URL carries a hash fragment (e.g. navigating
    // to /#ingredients via the nav), because the browser resolves the
    // fragment against the *document* URL, not just "same document". Once
    // that happens the clip silently no-ops and the iris renders unclipped
    // (poking above the eyelid). Fix: rewrite every local url(#id) reference
    // to an absolute URL (pathname/search, no hash) + id, and redo it any
    // time the hash changes since Next's client-side nav doesn't reload.
    const rewriteUrlRefs = () => {
      const base = window.location.href.split("#")[0];
      root.querySelectorAll<SVGElement>("[clip-path]").forEach((el) => {
        const current = el.getAttribute("clip-path");
        const match = current?.match(/url\(#?([^)]+)\)/);
        if (match) el.setAttribute("clip-path", `url(${base}#${match[1].replace(/^#/, "")})`);
      });
      root.querySelectorAll<SVGElement>("[filter]").forEach((el) => {
        const current = el.getAttribute("filter");
        const match = current?.match(/url\(#?([^)]+)\)/);
        if (match) el.setAttribute("filter", `url(${base}#${match[1].replace(/^#/, "")})`);
      });
    };
    rewriteUrlRefs();
    window.addEventListener("hashchange", rewriteUrlRefs);
    window.addEventListener("popstate", rewriteUrlRefs);

    const reduce =
      typeof window !== "undefined" &&
      window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    // ── pointer target, normalised -1..1 around the face ──
    let tx = 0,
      ty = 0; // where she should look
    let gx = 0,
      gy = 0; // smoothed gaze (eyes)
    let bx = 0,
      by = 0; // smoothed brow (lags gaze)
    let lastMove = performance.now();

    const aim = (cx: number, cy: number) => {
      const r = svg.getBoundingClientRect();
      const nx = (cx - (r.left + r.width / 2)) / (r.width / 2);
      const ny = (cy - (r.top + r.height / 2)) / (r.height / 2);
      tx = Math.max(-1, Math.min(1, nx));
      ty = Math.max(-1, Math.min(1, ny));
      lastMove = performance.now();
    };

    const onMouseMove = (e: MouseEvent) => aim(e.clientX, e.clientY);
    const onTouchMove = (e: TouchEvent) => {
      if (e.touches[0]) aim(e.touches[0].clientX, e.touches[0].clientY);
    };
    window.addEventListener("mousemove", onMouseMove);
    window.addEventListener("touchmove", onTouchMove, { passive: true });

    // ── click/tap "anger" flash — snap into a glare, hold, ease back ──
    let angerStart = -1,
      angerDirX = 0,
      angerDirY = 0;
    const angerLevel = (now: number) => {
      if (angerStart < 0) return 0;
      const t = now - angerStart,
        ATT = 120,
        HOLD = 900,
        DEC = 1600;
      if (t < ATT) return t / ATT;
      if (t < ATT + HOLD) return 1;
      if (t < ATT + HOLD + DEC) {
        const p = (t - ATT - HOLD) / DEC;
        return 1 - p * p * (3 - 2 * p);
      }
      angerStart = -1;
      return 0;
    };
    (svg as unknown as HTMLElement).style.cursor = "pointer";
    const onPointerDown = (e: PointerEvent) => {
      const r = svg.getBoundingClientRect();
      angerDirX = Math.max(-1, Math.min(1, (e.clientX - (r.left + r.width / 2)) / (r.width / 2)));
      angerDirY = Math.max(-1, Math.min(1, (e.clientY - (r.top + r.height / 2)) / (r.height / 2)));
      angerStart = performance.now();
    };
    svg.addEventListener("pointerdown", onPointerDown);

    // ── idle "look around" when no input for a while ──
    let idleT = 0,
      idleGoalX = 0,
      idleGoalY = 0;
    const idle = (now: number, dt: number) => {
      if (now - lastMove < 2600) return;
      idleT -= dt;
      if (idleT <= 0) {
        idleGoalX = (Math.random() * 2 - 1) * 0.7;
        idleGoalY = (Math.random() * 2 - 1) * 0.4;
        idleT = 900 + Math.random() * 1800;
      }
      tx += (idleGoalX - tx) * 0.02;
      ty += (idleGoalY - ty) * 0.02;
    };

    // ── micro-saccades: tiny rapid eye darts ──
    let sacX = 0,
      sacY = 0,
      sacNext = 0;
    const saccade = (now: number) => {
      if (now > sacNext) {
        sacX = (Math.random() * 2 - 1) * 0.5;
        sacY = (Math.random() * 2 - 1) * 0.35;
        sacNext = now + 400 + Math.random() * 1400;
      }
      sacX *= 0.85;
      sacY *= 0.85;
    };

    // ── blinks ──
    let blink = 0,
      blinkNext = performance.now() + 2000 + Math.random() * 2500,
      blinking = false,
      blinkT = 0;
    const doBlink = (now: number, dt: number) => {
      if (!blinking && now > blinkNext) {
        blinking = true;
        blinkT = 0;
      }
      if (blinking) {
        blinkT += dt;
        const dur = 130;
        const p = Math.min(1, blinkT / dur);
        blink = p < 0.5 ? p / 0.5 : 1 - (p - 0.5) / 0.5;
        if (blinkT >= dur) {
          blinking = false;
          blink = 0;
          blinkNext = now + 2600 + Math.random() * 3200;
        }
      }
    };

    let rafId = 0;
    let prev = performance.now();
    const frame = (now: number) => {
      const dt = Math.min(50, now - prev);
      prev = now;

      idle(now, dt);
      saccade(now);
      doBlink(now, dt);
      const anger = angerLevel(now);

      gx += (tx + sacX - gx) * CFG.follow;
      gy += (ty + sacY - gy) * CFG.follow;
      bx += (gx - bx) * CFG.browFollow;
      by += (gy - by) * CFG.browFollow;

      const px = gx * CFG.pupilX,
        py = Math.max(-1.8, Math.min(1.8, gy * CFG.pupilY));
      pL.style.transform = `translate(${px}px,${py}px)`;
      pR.style.transform = `translate(${px}px,${py}px)`;

      const squint = 1 - 0.12 * anger;
      const sy = (1 - 0.92 * blink) * squint;
      eL.style.transform = `scaleY(${sy})`;
      eR.style.transform = `scaleY(${(1 - 0.92 * Math.max(0, blink - 0.04)) * squint})`;

      const rot = bx * CFG.browRot,
        lift = -by * CFG.browLift;
      const furrow = anger * 9;
      const browDrop = anger * 2.6;
      bL.style.transform = `rotate(${rot + furrow}deg) translateY(${
        lift - (by < 0 ? by * 0.8 : 0) + browDrop
      }px)`;
      bR.style.transform = `rotate(${-rot - furrow}deg) translateY(${
        lift - (by < 0 ? by * 0.8 : 0) + browDrop
      }px)`;

      const breath = Math.sin(now / 900) * 0.4;
      const open = (1 + Math.max(0, -gy) * 0.06 + breath * 0.02) * (1 - 0.12 * anger);
      const grimace = 1 + 0.03 * anger;
      mouth.style.transform = `translateX(${gx * CFG.mouthShift}px) scaleX(${grimace}) scaleY(${open})`;

      // Forehead flame flicker — driven from this same rAF loop instead of
      // SMIL <animate> (which can stutter/restart when the SVG is injected
      // via innerHTML). Two out-of-phase sine waves stand in for the
      // original keyframe animation so the flicker never stops or jumps.
      if (turbulence && displacement) {
        const fx = 0.021 + 0.0035 * Math.sin(now / 1600);
        const fy = 0.0545 + 0.0085 * Math.sin(now / 1600 + 1.1);
        turbulence.setAttribute("baseFrequency", `${fx} ${fy}`);
        const flicker = 3.1 + 0.75 * Math.sin(now / 550) + 0.35 * Math.sin(now / 190 + 0.6);
        displacement.setAttribute("scale", String(flicker));
      }

      if (!reduce) {
        const t = now / 1000;
        const bob = Math.sin(t * 1.1);
        const sway = Math.sin(t * 0.7);
        const leanRot = angerDirX * anger * 2.2;
        const leanX = angerDirX * anger * 1.2;
        const leanY = angerDirY * anger * 0.6;
        const shrink = 1 - anger * 0.025;
        (head as unknown as HTMLElement).style.transform = `translateX(${leanX}px) translateY(${
          bob * 0.6 + leanY
        }px) rotate(${sway * 0.25 + leanRot}deg) scale(${(1 + bob * 0.004) * shrink})`;

        const swingL = Math.sin(t * 1.1 - 0.5) * 2.2 + gx * 1.5;
        const swingR = Math.sin(t * 1.1 - 0.7) * 2.2 + gx * 1.5;
        chL.style.transform = `rotate(${swingL}deg)`;
        chR.style.transform = `rotate(${swingR}deg)`;
      }

      rafId = requestAnimationFrame(frame);
    };

    if (reduce) {
      // Reduced motion: keep a gentle gaze-follow only, skip bob/sway/pendulum.
      rafId = requestAnimationFrame(frame);
    } else {
      rafId = requestAnimationFrame(frame);
    }

    return () => {
      cancelAnimationFrame(rafId);
      window.removeEventListener("mousemove", onMouseMove);
      window.removeEventListener("touchmove", onTouchMove);
      window.removeEventListener("hashchange", rewriteUrlRefs);
      window.removeEventListener("popstate", rewriteUrlRefs);
      svg.removeEventListener("pointerdown", onPointerDown);
    };
  }, [uid]);

  return (
    <div
      ref={rootRef}
      className={`living-hero${className ? ` ${className}` : ""}`}
      style={{ cursor: "pointer" }}
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
